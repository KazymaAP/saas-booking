# scripts/gen-db-types.ps1
# Generates lib/database.generated.ts from the public schema of a test database.
# Run after migrations 0001-0012 are applied to the TEST project (never production).
#
# Usage (from the project folder):
#   powershell -ExecutionPolicy Bypass -File .\scripts\gen-db-types.ps1 -DbUrl "postgresql://..."
#
# Output: lib/database.generated.ts. lib/database.types.ts is not touched.
# ASCII-only on purpose: Windows PowerShell 5.1 reads BOM-less UTF-8 as ANSI.
param(
  [Parameter(Mandatory = $true)][string]$DbUrl,
  # Pin the CLI version (e.g. 2.x.y) for reproducible output; 'latest' otherwise.
  [string]$CliVersion = 'latest'
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$out = Join-Path $root 'lib\database.generated.ts'

Write-Host "Generating types from schema public (supabase CLI: $CliVersion)..."
$generated = & npx --yes "supabase@$CliVersion" gen types typescript --db-url $DbUrl --schema public 2>$null
if ($LASTEXITCODE -ne 0) {
  throw "supabase gen types failed with exit code $LASTEXITCODE. Run the same command without 2>`$null to see the error."
}

$header = @(
  '// lib/database.generated.ts - generated by scripts/gen-db-types.ps1 from the database schema. Do not edit by hand.',
  "// Generated: $(Get-Date -Format 'yyyy-MM-dd HH:mm')",
  ''
)
[System.IO.File]::WriteAllLines($out, [string[]]($header + $generated), (New-Object System.Text.UTF8Encoding($false)))

# Check that the core tables are present in the generated file.
$required = @('vertical_templates', 'businesses', 'services', 'photos', 'bookings', 'admin_users',
  'email_accounts', 'rate_limits', 'audit_log', 'analytics_events', 'licenses')
$text = Get-Content -LiteralPath $out -Raw
$missing = @($required | Where-Object { $text -notmatch ("\b" + $_ + "\s*:\s*\{") })
if ($missing.Count -gt 0) {
  Write-Warning ("Tables not found in generated file: " + ($missing -join ', '))
} else {
  Write-Host "OK: all required tables are present. File: $out"
}
